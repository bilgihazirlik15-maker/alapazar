function translate(text) {
  if (language !== 'en') return text;
  if (translations[text]) return translations[text];
  return text.replace(/^Puan ([\d.]+)$/, 'Rating $1')
    .replace(/^(\d+) ürün$/, '$1 products')
    .replace(/^([\d.K]+) takipçi$/, '$1 followers')
    .replace(/^Üyeliğiniz oluşturuldu\. Hoş geldin, (.+)\.$/, 'Your account has been created. Welcome, $1.')
    .replace(/^Hoş geldin, (.+)\.$/, 'Welcome, $1.')
    .replace(/^(.+) için başvuru taslağı hazır\. Sonraki adımda satıcı panelini kuracağız\.$/, 'The application draft for $1 is ready. Next, we will set up the seller dashboard.');
}
const sourceText = new WeakMap();
const sourceAttributes = new WeakMap();
function localize(root) {
  if (root.nodeType === Node.TEXT_NODE) {
    if (root.parentElement?.closest('script,style,[data-no-translate]')) return;
    const value = root.nodeValue;
    const previous = sourceText.get(root);
    const source = previous && value === previous.result ? previous.source : value;
    const result = source.replace(/\S[\s\S]*\S|\S/, text => translate(text));
    sourceText.set(root, {source, result});
    if (value !== result) root.nodeValue = result;
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  if (root.matches('script,style,[data-no-translate]')) return;
  for (const attribute of ['placeholder', 'alt', 'aria-label']) {
    if (!root.hasAttribute(attribute)) continue;
    let originals = sourceAttributes.get(root);
    if (!originals) sourceAttributes.set(root, originals = {});
    const value = root.getAttribute(attribute);
    const old = originals[attribute];
    const source = old && old.result === value ? old.source : value;
    const result = translate(source);
    originals[attribute] = {source, result};
    if (value !== result) root.setAttribute(attribute, result);
  }
  root.childNodes.forEach(localize);
}
